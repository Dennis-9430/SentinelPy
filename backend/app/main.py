# ═════════════════════════════════════════════════════════════════════════
# SPA Catch-All — Serves the frontend for any non-API route
# ═════════════════════════════════════════════════════════════════════════
# IMPORTANT: This section must be at the END of the file, after
# ALL API routes.
#
# Approach: Route-based catch-all. FastAPI registers routes in order, so
# the API endpoints (`/api/*`, `/health`, etc.) match first.
# The `/{full_path:path}` at the end only captures what no previous
# endpoint matched — Vite static assets or SPA routes.
import os as _os

from fastapi.responses import FileResponse

_base = _os.path.dirname(__file__)
_spa_candidates = [
    _os.path.normpath(
        _os.path.join(_base, "..", "..", "frontend", "dist")
    ),  # local dev
    _os.path.normpath(_os.path.join(_base, "..", "frontend", "dist")),  # docker
]
_spa_dir = next((d for d in _spa_candidates if _os.path.isdir(d)), None)

if _spa_dir:
    _spa_index = _os.path.join(_spa_dir, "index.html")

    # MIME types for Vite assets
    _MIME_TYPES: dict[str, str] = {
        ".js": "application/javascript",
        ".mjs": "application/javascript",
        ".css": "text/css",
        ".json": "application/json",
        ".png": "image/png",
        ".jpg": "image/jpeg",
        ".jpeg": "image/jpeg",
        ".gif": "image/gif",
        ".svg": "image/svg+xml",
        ".ico": "image/x-icon",
        ".woff": "font/woff",
        ".woff2": "font/woff2",
        ".ttf": "font/ttf",
        ".eot": "application/vnd.ms-fontobject",
        ".webp": "image/webp",
        ".map": "application/json",
    }

    @app.get("/{full_path:path}", include_in_schema=False)
    async def serve_spa(full_path: str):
        """Serves static files from dist/ or falls back to index.html.

        API routes (`/api/*`) and explicit endpoints (`/health`,
        etc.) are already registered BEFORE this catch-all, so
        FastAPI matches them first and they never reach here.
        """
        # Serve the real file from dist/ if it exists
        candidate = _os.path.normpath(_os.path.join(_spa_dir, full_path))
        if _os.path.isfile(candidate):
            ext = _os.path.splitext(candidate)[1].lower()
            mime = _MIME_TYPES.get(ext, "application/octet-stream")
            return FileResponse(candidate, media_type=mime)

        # Fallback: index.html so React Router handles the route
        return FileResponse(_spa_index, media_type="text/html")

    logger.info("SPA catch-all active from: %s", _spa_dir)
else:
    logger.warning(
        "SPA directory not found. Searched in: %s. "
        "Run 'pnpm build' in frontend/ to serve the SPA.",
        _spa_candidates,
    )
