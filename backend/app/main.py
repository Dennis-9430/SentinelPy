async def crear_alerta_desde_engine(datos_alerta: dict) -> dict | None:
    """Callback that persists alerts generated by the correlation engine."""
    try:
        from app.database import async_session as db_session
        from app.models.alert import Alert

        async with db_session() as session:
            alerta = Alert(**datos_alerta)

            # Derive group_key from alert data
            source_ip = (
                datos_alerta.get("source_ip") or datos_alerta.get("source") or "unknown"
            )
            rule_id = str(alerta.rule_id)
            alerta.group_key = f"{rule_id}:{source_ip}"

            session.add(alerta)
            await session.commit()
            await session.refresh(alerta)

            alerta_dict = {
                "id": str(alerta.id),
                "rule_id": str(alerta.rule_id),
                "title": alerta.title,
                "severity": alerta.severity,
                "description": alerta.description,
                "status": alerta.status,
            }
            await multi_notifier.send_all(alerta_dict)
            logger.info(
                "Alert created by engine: %s | %s",
                alerta.title,
                alerta.severity,
            )
            return alerta_dict
    except Exception as e:
        logger.error("Error in alert callback: %s", e, exc_info=True)
        return None


async def actualizar_alerta_desde_engine(datos: dict):
    """Callback for updating counters within the time window.

    When the correlation engine detects an event within the time
    window of a rule, it calls this callback to increment event_count
    and update last_event_at on the existing alert.
    """
    try:
        from app.database import async_session as db_session
        from app.services.alert_service import AlertService

        async with db_session() as session:
            service = AlertService(session)
            await service.actualizar_contadores(
                rule_id=datos["rule_id"],
                event_count=datos["event_count"],
                last_event_at=datos["last_event_at"],
            )
    except Exception as e:
        logger.error("Error in update callback: %s", e, exc_info=True)


@asynccontextmanager
async def lifespan(app: FastAPI):
    """Handles the application lifecycle.

    Initializes DB, correlation engine, notifiers and collectors.
    """
    logger.info("Starting SentinelPy...")

    # ── Initialize database ────────────────────────────────────────
    try:
        from app.database import engine as db_engine
        from app.models.base import Base

        async with db_engine.begin() as conn:
            await conn.run_sync(Base.metadata.create_all)

        logger.info("Database tables verified/created")

        # ── Seed admin user ──────────────────────────────────────────
        try:
            from app.database import async_session as db_session

            async with db_session() as seed_session:
                auth_svc = AuthService(seed_session)
                try:
                    admin_user = await auth_svc.crear_usuario(
                        username=settings.admin_username,
                        password=settings.admin_password,
                        role="admin",
                    )
                    logger.info("Admin created: %s", admin_user.username)
                except ValueError:
                    logger.info("Admin already exists, skipping seed")

                # ── Seed demo agent (for docker-compose) ────────────
                try:
                    import os as _os

                    from app.services.agent_service import AgentService

                    demo_key = _os.environ.get(
                        "AGENT_API_KEY", "spy_demo-key-change-me"
                    )
                    agent_svc = AgentService(seed_session)
                    existing = await agent_svc.obtener_por_api_key(demo_key)
                    if existing:
                        logger.info("Demo agent already exists with the correct key")
                    else:
                        # Look up by name — may have an old key
                        from sqlalchemy import select as _sel

                        from app.models.agent import Agent

                        result = await seed_session.execute(
                            _sel(Agent).where(Agent.name == "demo-agent")
                        )
                        found = result.scalar_one_or_none()
                        demo_hash = AuthService.hash_password(demo_key)
                        if found:
                            found.api_key_hash = demo_hash
                            found.active = True
                            await seed_session.commit()
                            logger.info(
                                "Demo agent: key updated from AGENT_API_KEY env"
                            )
                        else:
                            demo_agent = Agent(
                                name="demo-agent",
                                hostname="demo-agent",
                                api_key_hash=demo_hash,
                                active=True,
                            )
                            seed_session.add(demo_agent)
                            await seed_session.commit()
                            logger.info(
                                "Agente demo creado (key from AGENT_API_KEY env)"
                            )
                except Exception as e:
                    logger.warning("Could not seed demo agent: %s", e)
        except Exception as e:
            logger.warning("Could not seed admin: %s", e)
    except Exception as e:
        logger.warning("Could not connect to the database: %s", e)

    # ── Load rules into the correlation engine ─────────────────────────
    try:
        from app.database import async_session as db_session
        from app.services.rule_service import RuleService

        async with db_session() as session:
            rule_service = RuleService(session)
            reglas = await rule_service.cargar_reglas_activas()
            engine.cargar_reglas(reglas)

        engine.registrar_callback(crear_alerta_desde_engine)
        engine.registrar_callback_actualizar(actualizar_alerta_desde_engine)
        app.state.engine = engine
        logger.info("Correlation engine: %d active rules", engine.reglas_activas)
    except Exception as e:
        logger.warning("Could not initialize the correlation engine: %s", e)
        app.state.engine = None

    # ── Configure notifiers ─────────────────────────────────────────
    multi_notifier.agregar(ConsoleNotifier())

    # EmailNotifier (only if SMTP configuration exists)
    if settings.smtp_user:
        from app.services.email_notifier import EmailNotifier

        multi_notifier.agregar(
            EmailNotifier(), min_severity=settings.notify_min_severity
        )
        logger.info(
            "EmailNotifier configured for severity >= %s",
            settings.notify_min_severity,
        )

    # WebhookNotifier (only if a URL is configured)
    if settings.webhook_url:
        from app.services.webhook_notifier import WebhookNotifier

        multi_notifier.agregar(
            WebhookNotifier(), min_severity=settings.notify_min_severity
        )
        logger.info(
            "WebhookNotifier configured for severity >= %s",
            settings.notify_min_severity,
        )

    app.state.notifier = multi_notifier
    logger.info("Notifiers configured")

    # ── Initialize analysis service ─────────────────────────────────
    try:
        from app.database import async_session as db_session

        analysis_service = AnalysisService(db_session)
        await analysis_service.init_async()
        app.state.analysis_service = analysis_service
        pipeline.analysis_service = analysis_service
        logger.info("Analysis service initialized")
    except Exception as e:
        logger.warning("Could not initialize analysis: %s", e)
        app.state.analysis_service = None

    # ── Start syslog collector ──────────────────────────────────────────
    try:
        from app.services.collector import SyslogCollector

        colector = SyslogCollector(pipeline)
        await colector.start()
        app.state.colector = colector
        logger.info("Collection system started")
    except Exception as e:
        logger.warning("Could not start the syslog collector: %s", e)
        app.state.colector = None

    app.state.pipeline = pipeline
    logger.info("SentinelPy started successfully")

    yield  # La app corre

    # ── Graceful shutdown ────────────────────────────────────────────────
    logger.info("Stopping SentinelPy...")

    if hasattr(app.state, "colector") and app.state.colector:
        await app.state.colector.stop()
        logger.info("Collectors stopped")

    if hasattr(app.state, "analysis_service") and app.state.analysis_service:
        await app.state.analysis_service.shutdown()

    logger.info("SentinelPy stopped")


